const labels = { youtube: "YouTube", facebook: "Facebook", instagram: "Instagram" };

export function SocialIcons({ className }: { className?: string }) {
  const links = (Object.keys(site.social) as (keyof typeof site.social)[]).filter((k) => site.social[k]);
  if (links.length === 0) return null;

  return (
    <ul className={cn("flex items-center gap-3", className)}>
      {links.map((key) => (
        <li key={key}>
          <a
            href={site.social[key]}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={labels[key]}
            className="grid size-10 place-items-center rounded-none border border-current/30 transition-colors hover:border-gold hover:text-gold"
          >
            <svg viewBox="0 0 24 24" fill="currentColor" className="size-4" aria-hidden>
              {icons[key]}
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
}
